const languageButton = document.querySelector(".language-toggle");
const menuButton = document.querySelector(".menu-toggle");
const nav = document.querySelector("#primary-nav");
const form = document.querySelector("#contact-form");
const formStatus = document.querySelector("#form-status");
let currentLanguage = "en";

function setLanguage(language) {
  currentLanguage = language;
  document.documentElement.lang = language;
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = copy[language][element.dataset.i18n];
    if (value !== undefined) element.innerHTML = value;
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    const value = copy[language][element.dataset.i18nPlaceholder];
    if (value !== undefined) element.placeholder = value;
  });
  languageButton.classList.toggle("is-ja", language === "ja");
  languageButton.setAttribute("aria-label", language === "en" ? "Switch language to Japanese" : "言語を英語に切り替える");
  const menuIsOpen = menuButton.getAttribute("aria-expanded") === "true";
  menuButton.setAttribute("aria-label", language === "en"
    ? (menuIsOpen ? "Close navigation menu" : "Open navigation menu")
    : (menuIsOpen ? "ナビゲーションメニューを閉じる" : "ナビゲーションメニューを開く"));
  document.title = language === "en"
    ? "Rubel Hossain — Web Designer & Front-end Developer"
    : "Rubel Hossain — ウェブデザイナー・フロントエンド開発者";
  formStatus.textContent = "";
  document.querySelectorAll(".field-error").forEach((error) => { error.textContent = ""; });
  document.querySelectorAll("[aria-invalid='true']").forEach((field) => field.removeAttribute("aria-invalid"));
}

languageButton.addEventListener("click", () => setLanguage(currentLanguage === "en" ? "ja" : "en"));

function closeMenu() {
  nav.classList.remove("is-open");
  menuButton.setAttribute("aria-expanded", "false");
  menuButton.setAttribute("aria-label", currentLanguage === "en" ? "Open navigation menu" : "ナビゲーションメニューを開く");
}
menuButton.addEventListener("click", () => {
  const isOpen = menuButton.getAttribute("aria-expanded") === "true";
  menuButton.setAttribute("aria-expanded", String(!isOpen));
  menuButton.setAttribute("aria-label", !isOpen
    ? (currentLanguage === "en" ? "Close navigation menu" : "ナビゲーションメニューを閉じる")
    : (currentLanguage === "en" ? "Open navigation menu" : "ナビゲーションメニューを開く"));
  nav.classList.toggle("is-open", !isOpen);
});
nav.querySelectorAll("a").forEach((link) => link.addEventListener("click", closeMenu));
document.addEventListener("keydown", (event) => {
  if (event.key === "Escape") closeMenu();
});

const sections = [...document.querySelectorAll("main section[id]")];
const navLinks = [...document.querySelectorAll(".nav-link")];
const activeObserver = new IntersectionObserver((entries) => {
  entries.forEach((entry) => {
    if (!entry.isIntersecting) return;
    navLinks.forEach((link) => {
      const sectionId = entry.target.id === "education" ? "journey" : entry.target.id;
      const active = link.dataset.section === sectionId;
      link.classList.toggle("is-active", active);
      if (active) link.setAttribute("aria-current", "location");
      else link.removeAttribute("aria-current");
    });
  });
}, { rootMargin: "-32% 0px -58% 0px", threshold: 0 });
sections.forEach((section) => activeObserver.observe(section));

const revealItems = document.querySelectorAll(".reveal");
if ("IntersectionObserver" in window && !window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
  const revealObserver = new IntersectionObserver((entries, observer) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("is-visible");
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.12 });
  revealItems.forEach((item) => revealObserver.observe(item));
} else {
  revealItems.forEach((item) => item.classList.add("is-visible"));
}

