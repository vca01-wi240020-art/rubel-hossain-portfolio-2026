const fieldRules = {
  name: (value) => value.trim().length >= 2 ? "" : value.trim() ? copy[currentLanguage].shortName : copy[currentLanguage].required,
  email: (value) => /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(value.trim()) ? "" : value.trim() ? copy[currentLanguage].invalidEmail : copy[currentLanguage].required,
  subject: (value) => value.trim().length >= 3 ? "" : value.trim() ? copy[currentLanguage].shortSubject : copy[currentLanguage].required,
  message: (value) => value.trim().length >= 10 ? "" : value.trim() ? copy[currentLanguage].shortMessage : copy[currentLanguage].required
};

form.addEventListener("submit", (event) => {
  event.preventDefault();
  formStatus.classList.remove("is-error");
  let valid = true;
  Object.entries(fieldRules).forEach(([name, validate]) => {
    const field = form.elements.namedItem(name);
    const error = form.querySelector(`[data-error-for="${name}"]`);
    const message = validate(field.value);
    error.textContent = message;
    field.setAttribute("aria-invalid", String(Boolean(message)));
    if (message) valid = false;
  });
  if (!valid) {
    formStatus.textContent = copy[currentLanguage].formError;
    formStatus.classList.add("is-error");
    form.querySelector('[aria-invalid="true"]').focus();
    return;
  }
  formStatus.textContent = copy[currentLanguage].formReview;
  formStatus.classList.remove("is-error");
});

form.addEventListener("input", (event) => {
  const field = event.target;
  if (!field.name || !fieldRules[field.name]) return;
  const message = fieldRules[field.name](field.value);
  form.querySelector(`[data-error-for="${field.name}"]`).textContent = message;
  field.setAttribute("aria-invalid", String(Boolean(message)));
  if (Object.values(fieldRules).every((validate) => {
    const control = form.elements.namedItem(Object.keys(fieldRules).find((key) => fieldRules[key] === validate));
    return !validate(control.value);
  })) {
    formStatus.textContent = "";
    formStatus.classList.remove("is-error");
  }
});
